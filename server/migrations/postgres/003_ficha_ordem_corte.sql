CREATE TABLE IF NOT EXISTS ordem_corte_linhas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL,
  ordem_corte_id INTEGER NOT NULL,
  cor TEXT NOT NULL,
  detalhes TEXT NOT NULL DEFAULT '',
  CONSTRAINT ordem_corte_linhas_fk_1 FOREIGN KEY (ordem_corte_id) REFERENCES ordens_corte (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ordem_corte_aviamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL,
  ordem_corte_id INTEGER NOT NULL,
  aviamento_id INTEGER,
  descricao TEXT NOT NULL,
  quantidade NUMERIC NOT NULL DEFAULT 0,
  unidade TEXT NOT NULL DEFAULT 'UN',
  observacoes TEXT NOT NULL DEFAULT '',
  CONSTRAINT ordem_corte_aviamentos_fk_1 FOREIGN KEY (ordem_corte_id) REFERENCES ordens_corte (id) ON DELETE CASCADE,
  CONSTRAINT ordem_corte_aviamentos_fk_2 FOREIGN KEY (aviamento_id) REFERENCES aviamentos (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS ordem_corte_oficinas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL,
  ordem_corte_id INTEGER NOT NULL,
  oficina TEXT NOT NULL DEFAULT '',
  costureiro TEXT NOT NULL DEFAULT '',
  observacoes TEXT NOT NULL DEFAULT '',
  CONSTRAINT ordem_corte_oficinas_fk_1 FOREIGN KEY (ordem_corte_id) REFERENCES ordens_corte (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ordem_corte_historico (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL,
  ordem_corte_id INTEGER NOT NULL,
  usuario_id INTEGER,
  acao TEXT NOT NULL,
  resumo TEXT NOT NULL DEFAULT '',
  payload TEXT NOT NULL DEFAULT '',
  criado_em TEXT NOT NULL DEFAULT (to_char((CURRENT_TIMESTAMP AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')),
  CONSTRAINT ordem_corte_historico_fk_1 FOREIGN KEY (ordem_corte_id) REFERENCES ordens_corte (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS ordem_corte_linhas_chave
  ON ordem_corte_linhas (ordem_corte_id, lower(cor));
CREATE INDEX IF NOT EXISTS ordem_corte_linhas_empresa
  ON ordem_corte_linhas (empresa_id, ordem_corte_id);
CREATE INDEX IF NOT EXISTS ordem_corte_aviamentos_empresa
  ON ordem_corte_aviamentos (empresa_id, ordem_corte_id);
CREATE INDEX IF NOT EXISTS ordem_corte_oficinas_empresa
  ON ordem_corte_oficinas (empresa_id, ordem_corte_id);
CREATE INDEX IF NOT EXISTS ordem_corte_historico_ordem
  ON ordem_corte_historico (empresa_id, ordem_corte_id, id);

ALTER TABLE ordem_corte_linhas ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS ordem_corte_linhas_empresa ON ordem_corte_linhas;
